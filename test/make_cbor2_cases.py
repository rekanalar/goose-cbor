#!/usr/bin/env python3
"""Make the cbor2 oracle cases for the goose-cbor package.

The script writes test/cbor2_cases.goose. Every case holds the bytes of a
value and the bytes that Python cbor2 writes for the same value with
canonical=True. The package test decodes the first bytes, encodes them
again, and compares the result with the second bytes.

    python3 test/make_cbor2_cases.py

The script uses only the standard library of Python and cbor2.
"""

import random
import sys

import cbor2


def random_value(rng, depth=0):
    kinds = ["int", "float", "text", "bytes", "bool", "null"]
    if depth < 2:
        kinds += ["array", "map"]
    kind = rng.choice(kinds)
    if kind == "int":
        return rng.choice([0, 1, 23, 24, 255, 256, 65535, 65536,
                           2 ** 31, 2 ** 32 - 1, -1, -24, -256, -70000])
    if kind == "float":
        return rng.choice([0.0, 1.5, -1.5, 3.25, 1e10, -1e-10, 2.0 ** 40])
    if kind == "text":
        return rng.choice(["", "a", "abc", "hello", "ünïcødé", "日本",
                           "x" * 40])
    if kind == "bytes":
        return rng.choice([b"", b"\x00", b"\x01\x02", bytes(range(20))])
    if kind == "bool":
        return rng.choice([True, False])
    if kind == "null":
        return None
    if kind == "array":
        return [random_value(rng, depth + 1) for _ in range(rng.randint(0, 4))]
    # A map. The keys stay text, so the key order of both sides is the
    # order of RFC 7049.
    keys = rng.sample(["a", "bb", "ccc", "dddd", "e"], rng.randint(1, 3))
    return {k: random_value(rng, depth + 1) for k in keys}


def hex_of(data):
    return data.hex()


def main():
    count = int(sys.argv[1]) if len(sys.argv) > 1 else 120
    rng = random.Random(20261108)
    cases = []
    while len(cases) < count:
        value = random_value(rng)
        data = cbor2.dumps(value, canonical=True)
        # The canonical form of cbor2 and the length-first form of the
        # package agree, so the package must give the same bytes again.
        cases.append((hex_of(data), hex_of(data)))

    out = ["// The oracle cases of Python cbor2. The file is generated by",
           "// test/make_cbor2_cases.py. Do not edit it by hand.",
           "",
           "namespace cbor2_cases;",
           "",
           "import std;",
           "",
           "// Each case holds the input bytes and the bytes of cbor2.",
           f"let CASE_INPUT: const u8[:][{len(cases)}] = ["]
    for a, _ in cases:
        out.append(f'    "{a}",')
    out.append("];")
    out.append("")
    out.append(f"let CASE_WANT: const u8[:][{len(cases)}] = [")
    for _, b in cases:
        out.append(f'    "{b}",')
    out.append("];")
    out.append("")

    path = "packages/goose-cbor/test/cbor2_cases.goose"
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(out))
    print(f"wrote {len(cases)} cases to {path}")


if __name__ == "__main__":
    main()
